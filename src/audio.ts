import type { ChordInfo } from './theory';

function interval(from: number, to: number) {
  return ((to - from) % 12 + 12) % 12;
}

function pitchAtOrAbove(pitchClass: number, minimum: number) {
  return minimum + interval(minimum, pitchClass);
}

/** Deterministic four-note cue, with a low root and chord tones above it. */
export function chordVoicing(chord: ChordInfo): readonly number[] {
  const bass = chord.root < 7 ? 48 + chord.root : 36 + chord.root;
  const dominant = interval(chord.root, chord.third) === 4 && interval(chord.root, chord.seventh) === 10;
  if (dominant) {
    const seventh = pitchAtOrAbove(chord.seventh, bass + 8);
    const third = pitchAtOrAbove(chord.third, seventh + 1);
    const fifth = pitchAtOrAbove(chord.fifth, third + 1);
    return [bass, seventh, third, fifth];
  }
  const third = pitchAtOrAbove(chord.third, bass + 1);
  const fifth = pitchAtOrAbove(chord.fifth, third + 1);
  const seventh = pitchAtOrAbove(chord.seventh, fifth + 1);
  return [bass, third, fifth, seventh];
}

/** Small, fixed Web Audio cues. No notes are composed or generated by AI. */
export class AudioEngine {
  private context: AudioContext | null = null;
  private oscillators = new Set<OscillatorNode>();
  private voices = new Map<number, { oscillator: OscillatorNode; envelope: GainNode }>();

  /** Keep browser checks silent when opened with ?muteAudio=1. */
  private connectOutput(envelope: GainNode, context: AudioContext) {
    if (new URLSearchParams(window.location?.search ?? '').get('muteAudio') !== '1') {
      envelope.connect(context.destination);
    }
  }

  async resume() {
    if (!this.context && 'AudioContext' in window) this.context = new AudioContext();
    if (this.context?.state === 'suspended') await this.context.resume();
  }

  private tone(pitch: number, duration: number, volume: number, type: OscillatorType, attack = 0.008) {
    const context = this.context;
    if (!context) return;
    const now = context.currentTime;
    const oscillator = context.createOscillator();
    const envelope = context.createGain();
    const soundingTime = Math.max(0.005, duration);
    const attackTime = Math.min(attack, soundingTime * 0.35);
    oscillator.type = type;
    oscillator.frequency.value = 440 * 2 ** ((pitch - 69) / 12);
    envelope.gain.setValueAtTime(0.0001, now);
    envelope.gain.exponentialRampToValueAtTime(Math.max(0.0002, volume), now + attackTime);
    envelope.gain.setValueAtTime(Math.max(0.0002, volume), now + Math.max(attackTime, soundingTime - 0.055));
    envelope.gain.exponentialRampToValueAtTime(0.0001, now + soundingTime);
    oscillator.connect(envelope);
    this.connectOutput(envelope, context);
    oscillator.onended = () => {
      oscillator.disconnect();
      envelope.disconnect();
      this.oscillators.delete(oscillator);
    };
    this.oscillators.add(oscillator);
    oscillator.start(now);
    oscillator.stop(now + soundingTime + 0.005);
  }

  click(accent: boolean) {
    this.tone(accent ? 89 : 84, 0.055, accent ? 0.13 : 0.075, 'square', 0.002);
  }

  chordCue(chord: ChordInfo) {
    for (const pitch of chordVoicing(chord)) this.tone(pitch, 0.34, 0.018, 'sine', 0.035);
  }

  playNote(pitch: number, seconds: number) {
    this.tone(pitch, seconds, 0.12, 'triangle', 0.012);
  }

  /** Starts a piano voice that lasts until noteOff, independent of timed cues. */
  noteOn(pitch: number) {
    const context = this.context;
    if (!context) return;
    this.noteOff(pitch);
    const now = context.currentTime;
    const oscillator = context.createOscillator();
    const envelope = context.createGain();
    oscillator.type = 'triangle';
    oscillator.frequency.value = 440 * 2 ** ((pitch - 69) / 12);
    envelope.gain.setValueAtTime(0.0001, now);
    envelope.gain.exponentialRampToValueAtTime(0.12, now + 0.012);
    oscillator.connect(envelope);
    this.connectOutput(envelope, context);
    const voice = { oscillator, envelope };
    this.voices.set(pitch, voice);
    oscillator.onended = () => {
      oscillator.disconnect();
      envelope.disconnect();
      if (this.voices.get(pitch) === voice) this.voices.delete(pitch);
    };
    oscillator.start(now);
  }

  noteOff(pitch: number) {
    const voice = this.voices.get(pitch);
    if (!voice || !this.context) return;
    this.voices.delete(pitch);
    const now = this.context.currentTime;
    voice.envelope.gain.cancelScheduledValues(now);
    voice.envelope.gain.setTargetAtTime(0.0001, now, 0.018);
    voice.oscillator.stop(now + 0.09);
  }

  /** Stop scheduled metronome, chord, and replay tones without cutting held keys. */
  stopTimed() {
    for (const oscillator of this.oscillators) {
      try { oscillator.stop(); } catch { /* already stopped */ }
    }
    this.oscillators.clear();
  }

  stopAll() {
    this.stopTimed();
    for (const { oscillator } of this.voices.values()) {
      try { oscillator.stop(); } catch { /* already stopped */ }
    }
    this.voices.clear();
  }
}
